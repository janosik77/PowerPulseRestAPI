using ClosedXML.Excel;
using PowerPulseRestAPI.Reports.Models;

namespace PowerPulseRestAPI.Reports.Generators;

public class ClosedXmlReportGenerator : IReportGenerator
{
    public string Format => "xlsx";

    public string ContentType =>
        "application/vnd.openxmlformats-officedocument.spreadsheetml.sheet";

    public string Extension => "xlsx";

    public byte[] Generate(
        AnalyticsReportData report,
        AnalyticsReportRequest request)
    {
        using var workbook =
            new XLWorkbook();

        AddSummarySheet(
            workbook,
            report,
            request);

        if (request.Sections.WorkHours)
        {
            AddWorkHoursSheet(
                workbook,
                report);
        }

        if (request.Sections.Projects)
        {
            AddProjectsSheet(
                workbook,
                report);
        }

        if (request.Sections.Materials)
        {
            AddMaterialsSheet(
                workbook,
                report);
        }

        if (request.Sections.Invoices)
        {
            AddInvoicesSheet(
                workbook,
                report);
        }

        if (request.Sections.Employees)
        {
            AddEmployeesSheet(
                workbook,
                report);
        }

        using var stream =
            new MemoryStream();

        workbook.SaveAs(stream);

        return stream.ToArray();
    }

    private static void AddSummarySheet(
        XLWorkbook workbook,
        AnalyticsReportData report,
        AnalyticsReportRequest request)
    {
        var ws =
            workbook.Worksheets.Add(
                "Summary");

        ws.Cell("A1").Value =
            report.Title;

        ws.Range("A1:D1")
            .Merge();

        var titleStyle =
            ws.Cell("A1").Style;

        titleStyle.Font.Bold = true;

        titleStyle.Font.FontSize =
            18;

        titleStyle.Font.FontColor =
            XLColor.White;

        titleStyle.Fill.BackgroundColor =
            XLColor.FromHtml(
                "#0B192C");

        ws.Row(1).Height =
            28;

        var row = 3;

        if (!string.IsNullOrWhiteSpace(
                report.Subtitle))
        {
            ws.Cell(
                row,
                1).Value =
                report.Subtitle;

            ws.Range(
                    row,
                    1,
                    row,
                    4)
                .Merge();

            row += 2;
        }

        WriteLabelValue(
            ws,
            row++,
            "Generated at",
            report.GeneratedAt
                .ToLocalTime()
                .ToString(
                    "dd MMM yyyy, HH:mm"));

        WriteLabelValue(
            ws,
            row++,
            "Generated by",
            report.GeneratedBy);

        WriteLabelValue(
            ws,
            row++,
            "Period",
            $"{report.Analytics.Period.From:dd MMM yyyy} - " +
            $"{report.Analytics.Period.To:dd MMM yyyy}");

        WriteLabelValue(
            ws,
            row++,
            "Project",
            report.ProjectLabel);

        WriteLabelValue(
            ws,
            row++,
            "Employee",
            report.EmployeeLabel);

        WriteLabelValue(
            ws,
            row++,
            "Customer",
            report.CustomerLabel);

        WriteLabelValue(
            ws,
            row++,
            "Currency",
            report.Analytics
                .Period
                .Currency);

        row += 2;

        if (request.Sections.Summary)
        {
            var summary =
                report.Analytics.Summary;

            ws.Cell(
                row,
                1).Value =
                "Active projects";

            ws.Cell(
                row,
                2).Value =
                "Work hours";

            ws.Cell(
                row,
                3).Value =
                "Invoice value";

            ws.Cell(
                row,
                4).Value =
                "Material cost";

            StyleHeader(
                ws.Range(
                    row,
                    1,
                    row,
                    4));

            row++;

            ws.Cell(
                row,
                1).Value =
                summary.ActiveProjects;

            ws.Cell(
                row,
                2).Value =
                summary.WorkHours;

            ws.Cell(
                row,
                3).Value =
                summary.InvoiceValue;

            ws.Cell(
                row,
                4).Value =
                summary.MaterialCost;

            ws.Cell(
                    row,
                    2)
                .Style
                .NumberFormat
                .Format =
                "0.00";

            ws.Cell(
                    row,
                    3)
                .Style
                .NumberFormat
                .Format =
                "#,##0.00";

            ws.Cell(
                    row,
                    4)
                .Style
                .NumberFormat
                .Format =
                "#,##0.00";
        }

        FinishSheet(
            ws,
            1);
    }

    private static void AddWorkHoursSheet(
        XLWorkbook workbook,
        AnalyticsReportData report)
    {
        var ws =
            workbook.Worksheets.Add(
                "Work Hours");

        WriteTitle(
            ws,
            "Work hours over time",
            2);

        ws.Cell(3, 1).Value =
            "Date";

        ws.Cell(3, 2).Value =
            "Hours";

        StyleHeader(
            ws.Range(
                3,
                1,
                3,
                2));

        var row = 4;

        foreach (var point in
                 report.Analytics
                     .WorkHoursTimeline)
        {
            ws.Cell(
                row,
                1).Value =
                point.Date.ToDateTime(
                    TimeOnly.MinValue);

            ws.Cell(
                    row,
                    1)
                .Style
                .DateFormat
                .Format =
                "dd mmm yyyy";

            ws.Cell(
                row,
                2).Value =
                point.Value;

            ws.Cell(
                    row,
                    2)
                .Style
                .NumberFormat
                .Format =
                "0.00";

            row++;
        }

        FinishSheet(
            ws,
            3);
    }

    private static void AddProjectsSheet(
        XLWorkbook workbook,
        AnalyticsReportData report)
    {
        var ws =
            workbook.Worksheets.Add(
                "Projects");

        WriteTitle(
            ws,
            "Project analytics",
            2);

        ws.Cell(3, 1).Value =
            "Project";

        ws.Cell(3, 2).Value =
            "Hours";

        StyleHeader(
            ws.Range(
                3,
                1,
                3,
                2));

        var row = 4;

        foreach (var project in
                 report.Analytics
                     .ProjectHours)
        {
            ws.Cell(
                row,
                1).Value =
                project.ProjectName;

            ws.Cell(
                row,
                2).Value =
                project.Hours;

            ws.Cell(
                    row,
                    2)
                .Style
                .NumberFormat
                .Format =
                "0.00";

            row++;
        }

        row += 2;

        ws.Cell(
            row,
            1).Value =
            "Project status";

        ws.Cell(
            row,
            2).Value =
            "Count";

        StyleHeader(
            ws.Range(
                row,
                1,
                row,
                2));

        row++;

        foreach (var status in
                 report.Analytics
                     .ProjectStatuses)
        {
            ws.Cell(
                row,
                1).Value =
                status.Label;

            ws.Cell(
                row,
                2).Value =
                status.Value;

            row++;
        }

        FinishSheet(
            ws,
            3);
    }

    private static void AddMaterialsSheet(
        XLWorkbook workbook,
        AnalyticsReportData report)
    {
        var ws =
            workbook.Worksheets.Add(
                "Materials");

        WriteTitle(
            ws,
            "Material consumption",
            6);

        string[] headers =
        {
            "Material",
            "Quantity",
            "Unit",
            "Unit price",
            "Total value",
            "Currency"
        };

        for (var i = 0;
             i < headers.Length;
             i++)
        {
            ws.Cell(
                3,
                i + 1).Value =
                headers[i];
        }

        StyleHeader(
            ws.Range(
                3,
                1,
                3,
                headers.Length));

        var row = 4;

        foreach (var item in
                 report.Analytics
                     .MaterialConsumption)
        {
            ws.Cell(
                row,
                1).Value =
                item.MaterialName;

            ws.Cell(
                row,
                2).Value =
                item.Quantity;

            ws.Cell(
                row,
                3).Value =
                item.Unit;

            ws.Cell(
                row,
                4).Value =
                item.UnitPrice;

            ws.Cell(
                row,
                5).Value =
                item.TotalValue;

            ws.Cell(
                row,
                6).Value =
                item.Currency;

            ws.Cell(
                    row,
                    2)
                .Style
                .NumberFormat
                .Format =
                "0.###";

            ws.Cell(
                    row,
                    4)
                .Style
                .NumberFormat
                .Format =
                "#,##0.00";

            ws.Cell(
                    row,
                    5)
                .Style
                .NumberFormat
                .Format =
                "#,##0.00";

            row++;
        }

        FinishSheet(
            ws,
            3);
    }

    private static void AddInvoicesSheet(
        XLWorkbook workbook,
        AnalyticsReportData report)
    {
        var ws =
            workbook.Worksheets.Add(
                "Invoices");

        WriteTitle(
            ws,
            "Invoice value over time",
            3);

        ws.Cell(3, 1).Value =
            "Date";

        ws.Cell(3, 2).Value =
            "Value";

        ws.Cell(3, 3).Value =
            "Currency";

        StyleHeader(
            ws.Range(
                3,
                1,
                3,
                3));

        var row = 4;

        foreach (var point in
                 report.Analytics
                     .InvoiceTimeline)
        {
            ws.Cell(
                row,
                1).Value =
                point.Date.ToDateTime(
                    TimeOnly.MinValue);

            ws.Cell(
                    row,
                    1)
                .Style
                .DateFormat
                .Format =
                "dd mmm yyyy";

            ws.Cell(
                row,
                2).Value =
                point.Value;

            ws.Cell(
                row,
                3).Value =
                report.Analytics
                    .Period
                    .Currency;

            ws.Cell(
                    row,
                    2)
                .Style
                .NumberFormat
                .Format =
                "#,##0.00";

            row++;
        }

        FinishSheet(
            ws,
            3);
    }

    private static void AddEmployeesSheet(
        XLWorkbook workbook,
        AnalyticsReportData report)
    {
        var ws =
            workbook.Worksheets.Add(
                "Employees");

        WriteTitle(
            ws,
            "Employee workload",
            2);

        ws.Cell(3, 1).Value =
            "Employee";

        ws.Cell(3, 2).Value =
            "Hours";

        StyleHeader(
            ws.Range(
                3,
                1,
                3,
                2));

        var row = 4;

        foreach (var employee in
                 report.Analytics
                     .EmployeeHours)
        {
            ws.Cell(
                row,
                1).Value =
                employee.EmployeeName;

            ws.Cell(
                row,
                2).Value =
                employee.Hours;

            ws.Cell(
                    row,
                    2)
                .Style
                .NumberFormat
                .Format =
                "0.00";

            row++;
        }

        FinishSheet(
            ws,
            3);
    }

    private static void WriteTitle(
        IXLWorksheet ws,
        string title,
        int columnCount)
    {
        ws.Cell(1, 1).Value =
            title;

        ws.Range(
                1,
                1,
                1,
                columnCount)
            .Merge();

        var style =
            ws.Cell(
                1,
                1)
                .Style;

        style.Font.Bold =
            true;

        style.Font.FontSize =
            16;

        style.Font.FontColor =
            XLColor.White;

        style.Fill.BackgroundColor =
            XLColor.FromHtml(
                "#0B192C");

        style.Alignment.Vertical =
            XLAlignmentVerticalValues.Center;

        ws.Row(1).Height =
            26;
    }

    private static void WriteLabelValue(
        IXLWorksheet ws,
        int row,
        string label,
        string value)
    {
        ws.Cell(
            row,
            1).Value =
            label;

        var style =
            ws.Cell(
                    row,
                    1)
                .Style;

        style.Font.Bold =
            true;

        style.Font.FontColor =
            XLColor.FromHtml(
                "#748393");

        ws.Cell(
            row,
            2).Value =
            value;
    }

    private static void StyleHeader(
        IXLRange range)
    {
        range.Style.Font.Bold =
            true;

        range.Style.Font.FontColor =
            XLColor.White;

        range.Style.Fill.BackgroundColor =
            XLColor.FromHtml(
                "#0B192C");

        range.Style.Alignment.Vertical =
            XLAlignmentVerticalValues.Center;

        range.Style.Alignment.Horizontal =
            XLAlignmentHorizontalValues.Left;
    }

    private static void FinishSheet(
        IXLWorksheet ws,
        int freezeRows)
    {
        ws.Columns()
            .AdjustToContents();

        foreach (var column in
                 ws.ColumnsUsed())
        {
            if (column.Width > 45)
            {
                column.Width = 45;
            }

            if (column.Width < 12)
            {
                column.Width = 12;
            }
        }

        foreach (var row in
                 ws.RowsUsed())
        {
            row.Style
                .Alignment
                .Vertical =
                XLAlignmentVerticalValues.Center;
        }

        if (freezeRows > 0)
        {
            ws.SheetView
                .FreezeRows(
                    freezeRows);
        }
    }
}
